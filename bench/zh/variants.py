"""Generate hard negatives: same topic, different entities.

A 30-session corpus makes retrieval trivial -- BM25 hit@10 was 1.000, which
means the benchmark cannot tell two systems apart. Real agent memories are not
like that: there are three projects with a media-publishing page, four test
machines, two rounds of E-drive cleanup. The hard part is not finding *a*
session about deployment, it is finding the one about *this* deployment.

So each original session gets a variant with its proper nouns, paths, IPs and
numbers swapped. The variant is a plausible memory that a real brain would
contain, and it is a hard negative for every question about the original: same
vocabulary, different facts.

Deliberately *not* generated by an LLM: a model asked to write "a similar but
different memory" tends to drift into a topic that is easy to distinguish. A
systematic entity swap keeps the surface form close, which is what makes the
negative hard.
"""

from __future__ import annotations

import json
from pathlib import Path

ZH_EVAL = Path(__file__).parent / "zh_eval.json"

# Entity substitutions. Order matters: longer, more specific strings first so
# that "媒体投稿界面" is not half-replaced by "媒体投稿".
SUBS: list[tuple[str, str]] = [
    # cities and machines
    ("203.0.113.42", "10.20.30.40"),
    ("/opt/demo-app", "/opt/alpha-test"),
    ("杭州", "成都"),
    ("demo-app.service", "alpha-test.service"),
    # project names
    ("媒体投稿", "素材分发"),
    ("已投文章", "已发素材"),
    ("media-schedules.json", "post-schedules.json"),
    ("/api/media/schedules", "/api/post/schedules"),
    ("/api/media/platforms", "/api/post/platforms"),
    ("/api/media/published-articles", "/api/post/published-items"),
    ("media-accounts.json", "post-accounts.json"),
    ("publishWithAutoRetry", "dispatchWithAutoRetry"),
    ("百家", "企鹅号"),
    ("头条", "网易号"),
    # files and tools
    ("E 盘", "F 盘"),
    ("117.2GB", "88.4GB"),
    ("110.06GB", "62.3GB"),
    ("7.55GB", "31.2GB"),
    ("117.61GB", "88.4GB"),
    ("robocopy", "rsync"),
    # code and versions
    ("keywords.py", "tokenizer.py"),
    ("第 443 行", "第 512 行"),
    ("4a29ae6", "9f13c2d"),
    ("beae716", "c07d914"),
    ("0.10.0", "0.9.7"),
    ("CodeWhale", "FleetShell"),
    # numbers
    ("9265", "7402"),
    ("7317", "5108"),
    ("34048", "21077"),
    ("380 秒", "240 秒"),
    ("八个", "六个"),
    ("八项", "六项"),
    # misc topics
    ("门户那个立绘", "官网那个横幅"),
    ("Brain4Agent", "AgentVault"),
    ("Engram", "Mnemo"),
    ("LongMemEval", "MemBench"),
    ("神经记忆", "上下文缓存"),
    ("日本机", "新加坡机"),
    ("工位机", "构建机"),
    ("PR #228", "PR #301"),
]

# Sessions that are safe to duplicate. Excluded: those whose content is about
# the *evaluation set itself* (s06-s10, s27, s28), because a swapped variant
# would collide with the questions being asked about the real one.
VARIANT_OK = {
    "s01",
    "s02",
    "s03",
    "s04",
    "s05",
    "s11",
    "s12",
    "s13",
    "s14",
    "s15",
    "s16",
    "s17",
    "s18",
    "s19",
    "s20",
    "s21",
    "s22",
    "s23",
    "s24",
    "s25",
    "s26",
    "s29",
    "s30",
}


def _swap(text: str) -> str:
    for old, new in SUBS:
        text = text.replace(old, new)
    return text


def _has_swap(text: str) -> bool:
    return any(old in text for old, _ in SUBS)


def create_variants(path: Path = ZH_EVAL) -> int:
    raw = json.loads(path.read_text(encoding="utf-8"))
    entries = raw["tasks"]
    corpus = entries[0]

    ids = list(corpus["haystack_session_ids"])
    dates = list(corpus["haystack_dates"])
    sessions = [list(s) for s in corpus["haystack_sessions"]]

    if any(sid.endswith("v") for sid in ids):
        print("variants already present, nothing to do")
        return 0

    added = 0
    for sid, date, sess in zip(ids, dates, sessions, strict=True):
        if sid not in VARIANT_OK:
            continue
        new_turns = []
        changed = False
        for msg in sess:
            content = _swap(msg["content"])
            if content != msg["content"]:
                changed = True
            new_turns.append({"role": msg["role"], "content": content})
        if not changed:
            continue
        corpus["haystack_session_ids"].append(f"{sid}v")
        corpus["haystack_dates"].append(date)
        corpus["haystack_sessions"].append(new_turns)
        added += 1

    for e in entries:
        e["haystack_session_ids"] = list(corpus["haystack_session_ids"])
        e["haystack_dates"] = list(corpus["haystack_dates"])
        e["haystack_sessions"] = [list(s) for s in corpus["haystack_sessions"]]

    raw["meta"]["sessions"] = len(corpus["haystack_session_ids"])
    raw["meta"]["variants"] = added
    raw["meta"]["note"] = (
        "One shared corpus. Sessions ending in 'v' are entity-swapped hard "
        "negatives: same topic and vocabulary, different facts."
    )

    path.write_text(json.dumps(raw, ensure_ascii=False, indent=2), encoding="utf-8")
    return added


def main() -> None:
    added = create_variants()
    raw = json.loads(ZH_EVAL.read_text(encoding="utf-8"))
    print(f"added {added} variant sessions")
    print(f"  total sessions: {raw['meta']['sessions']}")
    print(f"  questions:      {raw['meta']['questions']}")


if __name__ == "__main__":
    main()
